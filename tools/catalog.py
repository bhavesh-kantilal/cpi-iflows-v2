"""Generate _reference/CATALOG.md: functions, parameters and patterns found in the reference mappings.

    py -I tools/catalog.py            write _reference/CATALOG.md
    py -I tools/catalog.py --check    exit 1 if CATALOG.md is not up to date

Everything in the catalog is COUNTED from the .mmap files (toolkit reader cpimm/model.py), never written by hand.
Evidence level per reference (CLAUDE.md learning loop):
  L1 = original export from the user (SAP CPI/PI)       L3 = generated by this toolkit, tested by the user in CPI
A reference is L3 when its name is a build in mappings/*/build/; everything else is L1.
Distinct files only: an .mmap that is byte-identical to one already read (e.g. the copy inside an iFlow export) is skipped.
"""
from __future__ import annotations

import sys
from collections import Counter, defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
sys.stdout.reconfigure(encoding="utf-8")

from cpimm.model import FormatError, Func, Ref, Src, load   # noqa: E402

REPO = Path(__file__).resolve().parent.parent
REF = REPO / "_reference"
OUT = REF / "CATALOG.md"


def references():
    generated = {p.stem for p in REPO.glob("mappings/*/build/*.zip")}
    seen, refs, skipped = set(), [], []
    for p in sorted(REF.rglob("*.mmap"), key=lambda q: (len(q.parts), str(q).lower())):
        data = p.read_bytes()
        if data in seen:
            continue
        seen.add(data)
        try:
            m = load(p)
        except FormatError as e:
            skipped.append(f"{p.relative_to(REF).as_posix()} ({e})")
            continue
        parts = p.relative_to(REF).parts
        code = parts[0] if parts[1] == "mapping" else f"{parts[0]} › {p.stem}"     # standalone vs inside an iFlow
        refs.append((code, "L3" if m.name in generated else "L1", p.relative_to(REF).as_posix(), m))
    return refs, skipped


def nodes(m):
    """uid -> node, so Refs can be followed."""
    by_uid = {}

    def walk(x):
        if isinstance(x, (Func, Src)) and x.uid:
            by_uid.setdefault(x.uid, x)
        if isinstance(x, Func):
            for a in x.args:
                walk(a.expr)
    for t in m.targets:
        if t.expr is not None:
            walk(t.expr)
    return by_uid


def walk_all(x, by_uid, parent=None, seen=None):
    """Yield (node, parent_func) for every node, following each shared node once."""
    seen = set() if seen is None else seen
    if isinstance(x, Ref):
        if x.uid in seen:
            return
        x = by_uid[x.uid]
    if isinstance(x, (Func, Src)) and x.uid:
        if x.uid in seen:
            return
        seen.add(x.uid)
    yield x, parent
    if isinstance(x, Func):
        for a in x.args:
            yield from walk_all(a.expr, by_uid, x, seen)


def skeleton(x, by_uid, depth=4):
    """Function chain of a target, names only, e.g. SplitByValue(removeContexts(ifWithoutElse(…)))."""
    if isinstance(x, Ref):
        x = by_uid[x.uid]
    if isinstance(x, Src):
        return "src"
    if x.fname == "const" and x.fns == "dflt":
        return "const"
    name = x.fname if x.fns == "dflt" else f"UDF:{x.fns}.{x.fname}"
    if depth == 0 or not x.args:
        return name
    return f"{name}(" + ", ".join(skeleton(a.expr, by_uid, depth - 1) for a in x.args) + ")"


def local(path):
    return "/".join(s.split(":")[-1] for s in path.split("/"))


def main():
    refs, skipped = references()
    fn_count, fn_files, fn_pins = Counter(), defaultdict(set), defaultdict(set)
    params = defaultdict(Counter)                 # fname -> Counter("name=value")
    contexts, attr_contexts = [], []
    copy_vs_uoam = defaultdict(list)
    createif = []
    fix = []
    froms = []
    chains = Counter()
    chain_files = defaultdict(set)
    summary = []
    for code, lvl, rel, m in refs:
        by_uid = nodes(m)
        groups = {t.group for t in m.targets if t.group}
        dups = sorted({t.path for t in m.targets if "[" in t.path})
        summary.append((code, lvl, rel, m, len(groups), len(dups), sum(t.disabled for t in m.targets)))
        tag = f"{code} ({lvl})"
        for t in m.targets:
            if t.expr is None:
                continue
            if getattr(t, "out", None):
                froms.append((tag, t.path, f"target from={t.out}"))
            chains[skeleton(t.expr, by_uid, 3)] += 1
            chain_files[skeleton(t.expr, by_uid, 3)].add(code)
            for n, parent in walk_all(t.expr, by_uid):
                if isinstance(n, Src) and n.context:
                    item = (tag, local(n.path), local(n.context), t.path)
                    (attr_contexts if "/@" in n.path else contexts).append(item)
                if not isinstance(n, Func):
                    continue
                key = n.fname if n.fns == "dflt" else f"UDF {n.fns}.{n.fname}"
                fn_count[key] += 1
                fn_files[key].add(code)
                fn_pins[key].add(len(n.args))
                for a in n.args:
                    if a.out:
                        froms.append((tag, t.path, f"{key} input from={a.out}"))
                for p in n.params or []:
                    if p.table is not None:
                        params[key][f"{p.name}=<table {len(p.table)} rows>"] += 1
                    elif p.calend is not None:
                        params[key][f"{p.name}=<calend {','.join(k + '=' + v for k, v in p.calend)}>"] += 1
                    elif n.fname != "const":
                        params[key][f"{p.name}={p.text!r}"] += 1
                if n.fname in ("CopyValue", "useOneAsMany"):
                    copy_vs_uoam[n.fname].append((tag, t.path))
                if n.fname == "createIf":
                    wrapped = parent.fname if isinstance(parent, Func) else "(target)"
                    createif.append((tag, t.path, wrapped, skeleton(n, by_uid, 3)))
                if n.fname in ("FixValues", "valuemap"):
                    d = {p.name: p.text for p in n.params or [] if p.text is not None}
                    fix.append((tag, n.fname, d.get("vmstrategy"), d.get("vmdefault"), t.path))

    L = []
    w = L.append
    w("# CATALOG — functions and patterns in the reference mappings")
    w("")
    w("**Generated by `py -I tools/catalog.py`. Do not edit by hand.** Counted from the distinct `.mmap` files in "
      "`_reference/` with the toolkit reader. L1 = original export from the user; L3 = generated by this toolkit "
      "and tested by the user in CPI (see `_reference/README.md`). L3 shows what *works*; only L1 shows how SAP "
      "itself writes a mapping.")
    w("")
    w("## 1. References read")
    w("| Code | Level | File | Source link | Target link | Targets | Groups | Dup. subtrees | Disabled | UDF scripts |")
    w("|---|---|---|---|---|---|---|---|---|---|")
    for code, lvl, rel, m, g, d, dis in summary:
        lk = lambda l: f"{l.type_id}: " + " · ".join(e for e in l.elems if e)
        w(f"| {code} | {lvl} | `{rel}` | {lk(m.source)} | {lk(m.target)} | {len(m.targets)} | {g} | {d} | {dis} | "
          f"{', '.join(m.udfs) or '—'} |")
    if skipped:
        w("")
        w("Not read (not in the standard envelope): " + "; ".join(f"`{s}`" for s in skipped))
    w("")
    w("## 2. Functions")
    w("| Function | Uses | Input pins seen | Parameters seen (count) | In |")
    w("|---|---|---|---|---|")
    for key in sorted(fn_count, key=lambda k: (k.startswith("UDF"), -fn_count[k], k)):
        ps = "; ".join(f"`{p}` ({c})" for p, c in sorted(params[key].items(), key=lambda kv: -kv[1])[:8]) or "—"
        w(f"| `{key}` | {fn_count[key]} | {', '.join(map(str, sorted(fn_pins[key])))} | {ps} | "
          f"{', '.join(sorted(fn_files[key]))} |")
    w("")
    w("## 3. Patterns")
    w("### 3.1 `context=` on attributes")
    w("| Reference | Attribute | Context | Target |")
    w("|---|---|---|---|")
    for r in attr_contexts or [("—", "", "", "")]:
        w("| " + " | ".join(f"`{x}`" if x and i else x for i, x in enumerate(r)) + " |")
    w("")
    w("### 3.2 `context=` on elements")
    w("| Reference | Field | Context | Target |")
    w("|---|---|---|---|")
    for r in contexts or [("—", "", "", "")]:
        w("| " + " | ".join(f"`{x}`" if x and i else x for i, x in enumerate(r)) + " |")
    w("")
    w("### 3.3 Header value on repeating targets: `CopyValue` vs `useOneAsMany`")
    w("| Function | Reference | Target |")
    w("|---|---|---|")
    for f in ("CopyValue", "useOneAsMany"):
        for tag, path in copy_vs_uoam.get(f, []):
            w(f"| `{f}` | {tag} | `{path}` |")
    w("")
    w("### 3.4 `createIf`: what consumes it")
    w("| Reference | Target | Consumed by | Chain |")
    w("|---|---|---|---|")
    for tag, path, wrapped, sk in createif:
        w(f"| {tag} | `{path}` | `{wrapped}` | `{sk}` |")
    w("")
    w("### 3.5 FixValues / valuemap strategies")
    w("| Reference | Function | vmstrategy | vmdefault | Target |")
    w("|---|---|---|---|---|")
    for tag, fname, st, df, path in fix:
        w(f"| {tag} | `{fname}` | `{st}` | `{df!r}` | `{path}` |")
    w("")
    w("### 3.6 Multi-output UDFs (`from=n`)")
    w("| Reference | Target | Where |")
    w("|---|---|---|")
    for r in froms or [("—", "", "")]:
        w(f"| {r[0]} | `{r[1]}` | {r[2]} |")
    w("")
    w("### 3.7 Most common target chains (function names, 3 levels)")
    w("| Chain | Targets | In |")
    w("|---|---|---|")
    for sk, c in chains.most_common(40):
        w(f"| `{sk}` | {c} | {', '.join(sorted(chain_files[sk]))} |")
    text = "\n".join(L) + "\n"
    if "--check" in sys.argv:
        ok = OUT.exists() and OUT.read_text(encoding="utf-8") == text
        print("CATALOG.md up to date" if ok else "CATALOG.md is out of date: run py -I tools/catalog.py")
        return 0 if ok else 1
    OUT.write_text(text, encoding="utf-8", newline="")
    print(f"written {OUT.relative_to(REPO)}: {len(refs)} references, {len(fn_count)} functions")
    return 0


if __name__ == "__main__":
    sys.exit(main())
